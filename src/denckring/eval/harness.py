"""Level 3: the scoreboard. This is the CI gate and the unattended-run criterion."""

from __future__ import annotations

from collections import Counter
from functools import cache
from importlib.resources import files
from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field

from denckring.core import catalogue
from denckring.core.errors import DenckringError
from denckring.core.protocol import Lang, LanguagePack
from denckring.core.registry import all_procedures, get
from denckring.lang import get_pack

GOLDEN_DIR = Path(str(files("denckring") / "eval" / "fixtures" / "golden"))
GAPS_FILE = Path(str(files("denckring") / "eval" / "fixtures" / "evidence-gaps.yaml"))


#: Where a golden case's text came from, which is a different question from
#: whether it passes. An implementation and its own examples can agree while both
#: encode the wrong reading of a constraint, and nothing in a green suite says
#: which of the two you are looking at.
#:
#: `external` means the text comes from outside this repository — a published
#: work, or a form so widely attested that it has no single author. It is the
#: only value that is evidence about the *interpretation* rather than about the
#: code.
#:
#: `constructed` means it was written for this suite. That is not a defect: a
#: counterexample usually has to be built, because published sources record forms
#: that succeed and rarely the near-misses that a checker most needs to reject.
#:
#: `self-generated` means the implementation produced it and the checker accepted
#: it back. Those cases are worth keeping and worth naming, because they test the
#: round trip and cannot test the reading: a generator and a checker that share a
#: misunderstanding agree perfectly.
#:
#: Explicit rather than inferred from the `source` prose. Deriving it by looking
#: for an English "constructed" prefix mis-filed a German case that says
#: `konstruiertes Beispiel` and three that say they were generated by the row's
#: own `apply`.
CaseProvenance = Literal["external", "constructed", "self-generated"]


class GoldenCase(BaseModel):
    """One recorded example, positive or negative, for a procedure.

    Published as `denckring.GoldenCase` and read through `denckring.golden_cases`,
    which documents the fields; the rest of this module stays internal.
    """

    procedure: str
    lang: Lang = "en"
    name: str
    text: str
    params: dict[str, Any] = Field(default_factory=dict)
    satisfied: bool
    source: str | None = None
    #: Defaults to `constructed`, which is what a case is unless it says
    #: otherwise — the conservative reading, and the one that cannot overstate
    #: how much independent evidence this suite carries.
    provenance: CaseProvenance = "constructed"
    min_score: float | None = None
    max_score: float | None = None
    #: Capabilities this *case* needs, beyond what its row declares. A row states
    #: what its checker calls; a case may additionally depend on which answer it
    #: gets. `alexandrine` asks only for `syllables.heuristic`, but the Gryphius
    #: case's verdict turns on the German dictionary — with it a line reads
    #: fourteen syllables and the case fails as recorded, without it the heuristic
    #: reads twelve and the same text satisfies. Unmet, the case is blocked in the
    #: same way a row-level gap is, rather than reported as a wrong answer.
    requires: list[str] = Field(default_factory=list)


class CaseResult(BaseModel):
    case: str
    procedure: str
    lang: Lang
    passed: bool
    detail: str | None = None
    #: The `DenckringError.code` of the refusal, where the case failed by
    #: raising rather than by disagreeing. `detail` has always carried the
    #: message and threw away the one machine-readable field the error has, so
    #: a consumer wanting to tell "this install lacks the data" from "this
    #: checker is wrong" had to match English prose for it.
    code: str | None = None


#: Why an implemented row has no externally sourced golden case (ADR 0062). Shipped
#: cases quote public-domain text only, so the first two say no case can be added
#: while that policy stands, and the last two that one might be:
#:
#: `in_copyright`: exemplars exist, and none is public domain;
#: `after_cutoff`: the form postdates 1930, so no public-domain exemplar can exist;
#: `unsupported_language`: exemplars exist only in languages no pack covers;
#: `none_found`: none located yet, and the note names what was searched.
GapReason = Literal["in_copyright", "after_cutoff", "unsupported_language", "none_found"]


class EvidenceGap(BaseModel):
    """One entry of `evidence-gaps.yaml`: a row's reason, and what it rests on."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    reason: GapReason
    note: str


class CorpusShare(BaseModel):
    """How a row's golden cases divide by where their text came from (ADR 0062).

    `external_passing` and `external_failing` split the externally sourced cases by
    the verdict each records, since a published near-miss is evidence about the
    reading too. Counted over every shipped case, whatever this install can run, so
    the answer is the same on every install. `gap` is the reason the evidence gap
    registry gives for the row, or `None`; the corpus guards keep it `None` on every
    row with an external case.
    """

    model_config = ConfigDict(frozen=True)

    external_passing: int
    external_failing: int
    constructed: int
    self_generated: int
    gap: GapReason | None


class EvidenceCoverage(BaseModel):
    """Implemented rows split by whether a published text stands behind their reading.

    `unexplained` is held at 0 by `tests/test_corpus_provenance.py`, and printed
    anyway: a line that only ever showed two numbers could not show the guard broken.
    """

    evidenced: int
    explained: int
    unexplained: int

    def line(self) -> str:
        return (
            f"{self.evidenced} rows externally evidenced · "
            f"{self.explained} explained · "
            f"{self.unexplained} unexplained"
        )


class Coverage(BaseModel):
    """The project metric.

    `implementable` excludes rows that can never have a checker, so the gap
    between it and `implemented` describes work that can actually be done.

    Every field but `instruments` counts the `verfahren` layer alone (ADR 0033 D3).
    Folding both layers into one total would make `155 catalogued` mean something
    different from what it meant in every ADR that recorded it, and the 500 target is
    a target for `verfahren` (D4), so the instrument count is reported beside these
    numbers rather than inside them.
    """

    catalogued: int
    implementable: int
    implemented: int
    validated: int
    unreachable: int
    #: Reads 0 until the first instrument entry lands, which is the expected state
    #: after ADR 0033 rather than an unfinished migration.
    instruments: int
    #: Printed on a line of its own, like `instruments`, so the five-part line keeps
    #: the meaning every ADR before 0062 recorded for it.
    evidence: EvidenceCoverage

    def line(self) -> str:
        return (
            f"{self.catalogued} catalogued · "
            f"{self.implementable} implementable · "
            f"{self.implemented} implemented · "
            f"{self.validated} validated · "
            f"{self.unreachable} not mechanically checkable"
        )

    def instrument_line(self) -> str:
        """The second counter, on a line of its own so the first keeps its meaning."""
        return f"{self.instruments} instruments catalogued"


class CorpusProvenance(BaseModel):
    """How much of the corpus is evidence about the reading rather than the code.

    Reported beside the pass count because the two answer different questions and
    the pass count was being read as if it answered both. 532 cases agreeing with
    the implementation is a statement about consistency; how many of them came
    from outside this repository is the only part of it that is a statement about
    whether the constraint was understood correctly.
    """

    external: int = 0
    constructed: int = 0
    self_generated: int = 0

    @property
    def total(self) -> int:
        return self.external + self.constructed + self.self_generated

    def line(self) -> str:
        share = f"{self.external / self.total * 100:.1f}%" if self.total else "0.0%"
        return (
            f"{self.external} externally sourced ({share}) · "
            f"{self.constructed} constructed · "
            f"{self.self_generated} self-generated"
        )


def unmet_requirements(case: GoldenCase, pack: LanguagePack) -> list[str]:
    """Which of the case's own capability requirements this pack cannot meet."""
    return [name for name in case.requires if name not in pack.capabilities]


def corpus_provenance(cases: list[GoldenCase] | None = None) -> CorpusProvenance:
    """Count the cases by where their text came from."""
    counted = Counter(case.provenance for case in (cases if cases is not None else golden_cases()))
    return CorpusProvenance(
        external=counted["external"],
        constructed=counted["constructed"],
        self_generated=counted["self-generated"],
    )


class Scoreboard(BaseModel):
    results: list[CaseResult]
    coverage: Coverage
    #: Defaulted rather than required, so a caller building a Scoreboard by hand
    #: — the tests do — does not have to supply a corpus it is not describing.
    provenance: CorpusProvenance = Field(default_factory=CorpusProvenance)

    @property
    def passed(self) -> int:
        return sum(1 for r in self.results if r.passed)

    @property
    def failed(self) -> int:
        return sum(1 for r in self.results if not r.passed)

    @property
    def ok(self) -> bool:
        return self.failed == 0


def golden_cases() -> list[GoldenCase]:
    """Every shipped golden example, across every procedure."""
    cases: list[GoldenCase] = []
    for path in sorted(GOLDEN_DIR.glob("*.yaml")):
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
        default_lang = data.get("lang", "en")
        for row in data["cases"]:
            # A case may override the file's language, so English and German
            # examples of the same procedure live in one file.
            cases.append(GoldenCase(procedure=data["procedure"], **{"lang": default_lang, **row}))
    return cases


def implemented_ids() -> list[str]:
    """Every `verfahren` procedure that has a registered module.

    Intersected with the catalogue rather than read straight off the registry, so
    that an instrument shipping a checker of its own could not move the five-part
    line by the back door. `tests/test_registry.py` holds registered ids to a subset
    of the catalogue, so nothing else is lost in the intersection.
    """
    return sorted(set(all_procedures()) & set(catalogue.ids("verfahren")))


def implemented_rows() -> set[str]:
    """`implemented_ids` as a set, the shape the evidence guards compare against."""
    return set(implemented_ids())


@cache
def _gaps() -> dict[str, EvidenceGap]:
    data = yaml.safe_load(GAPS_FILE.read_text(encoding="utf-8")) or {}
    return {pid: EvidenceGap.model_validate(entry) for pid, entry in data.items()}


def evidence_gaps() -> dict[str, EvidenceGap]:
    """The registry of rows with no external case, and why (ADR 0062).

    A copy, so a caller editing the result cannot change what the next caller reads.
    """
    return dict(_gaps())


@cache
def _shares() -> dict[str, Counter[str]]:
    """Per row, its cases counted under the keys of `CorpusShare`. Cached because
    `describe` asks once per row and the fixtures are package data, fixed at runtime."""
    counted: dict[str, Counter[str]] = {}
    for case in golden_cases():
        key = case.provenance.replace("-", "_")
        if case.provenance == "external":
            key = "external_passing" if case.satisfied else "external_failing"
        counted.setdefault(case.procedure, Counter())[key] += 1
    return counted


def corpus_share(procedure_id: str) -> CorpusShare:
    """Count one row's golden cases by provenance and recorded verdict (ADR 0062)."""
    counted = _shares().get(procedure_id, Counter())
    gap = _gaps().get(procedure_id)
    return CorpusShare(
        external_passing=counted["external_passing"],
        external_failing=counted["external_failing"],
        constructed=counted["constructed"],
        self_generated=counted["self_generated"],
        gap=gap.reason if gap is not None else None,
    )


def evidence_coverage() -> EvidenceCoverage:
    """How many implemented rows are evidenced, explained by a gap entry, or neither."""
    shares = _shares()
    evidenced = explained = unexplained = 0
    for pid in implemented_ids():
        counted = shares.get(pid, Counter())
        if counted["external_passing"] + counted["external_failing"]:
            evidenced += 1
        elif pid in _gaps():
            explained += 1
        else:
            unexplained += 1
    return EvidenceCoverage(evidenced=evidenced, explained=explained, unexplained=unexplained)


def validated_ids() -> list[str]:
    """Every implemented procedure that also has golden examples."""
    with_fixtures = {c.procedure for c in golden_cases()}
    return sorted(with_fixtures & set(implemented_ids()))


def implementable_ids() -> list[str]:
    """`verfahren` rows that could have a checker, whether or not they do."""
    return sorted(
        pid for pid in catalogue.ids("verfahren") if catalogue.get(pid).checkability != "none"
    )


def status() -> Coverage:
    """Count the catalogue against what is implementable, implemented and validated."""
    catalogued = catalogue.ids("verfahren")
    implementable = implementable_ids()
    return Coverage(
        catalogued=len(catalogued),
        implementable=len(implementable),
        implemented=len(implemented_ids()),
        validated=len(validated_ids()),
        unreachable=len(catalogued) - len(implementable),
        instruments=len(catalogue.ids("instrument")),
        evidence=evidence_coverage(),
    )


def run() -> Scoreboard:
    """Run every golden case through its procedure."""
    results: list[CaseResult] = []
    cases = golden_cases()
    for case in cases:
        detail: str | None = None
        code: str | None = None
        # Checked before running, because the point is that running it would give
        # an answer that is about the installed data rather than about the text.
        missing = unmet_requirements(case, get_pack(case.lang))
        if missing:
            results.append(
                CaseResult(
                    case=case.name,
                    procedure=case.procedure,
                    lang=case.lang,
                    passed=False,
                    detail=f"needs {', '.join(missing)}",
                    code="missing_capability",
                )
            )
            continue
        try:
            report = get(case.procedure).check(case.text, lang=case.lang, **case.params)
            passed = report.satisfied is case.satisfied
            if passed and case.min_score is not None:
                passed = report.score >= case.min_score
            if passed and case.max_score is not None:
                passed = report.score <= case.max_score
            if not passed:
                detail = f"satisfied={report.satisfied} score={report.score:.3f}"
        except DenckringError as exc:
            passed = False
            detail = str(exc)
            code = exc.code
        results.append(
            CaseResult(
                case=case.name,
                procedure=case.procedure,
                lang=case.lang,
                passed=passed,
                detail=detail,
                code=code,
            )
        )
    return Scoreboard(results=results, coverage=status(), provenance=corpus_provenance(cases))
